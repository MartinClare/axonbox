const TABLES: Record<UiLocale, Dict> = { "zh-Hant": zh, en };

export function translate(
  locale: UiLocale,
  key: string,
  vars?: Record<string, string | number>,
): string {
  const table = TABLES[locale] || zh;
  let text = table[key] ?? zh[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      text = text.replaceAll(`{${k}}`, String(v));
    }
  }
  return text;
}

export function domainLabelMap(
  locale: UiLocale,
  prefix: string,
  keys: string[],
): Record<string, string> {
  const out: Record<string, string> = {};
  for (const k of keys) {
    out[k] = translate(locale, `${prefix}.${k}`);
  }
  return out;
}
